"use client"

import { shade as shadeColor } from "../lib/color"

export type GashaponMachinePhase = "idle" | "windUp" | "dropping" | "opening"

type GashaponMachineArtProps = {
  machineColor: string
  decorativeColor: string
  phase?: GashaponMachinePhase
}

// Intentionally not `@chatbotx.io/ui`'s `hexToRgb`, mirroring
// `jackpot-machine-art.tsx`/`lucky-wheel-art.tsx`: this fallback tuple keeps
// malformed input a visible color instead of silently rendering black.
const FALLBACK_RGB: [number, number, number] = [219, 39, 119]

function shade(hex: string, amount: number): string {
  return shadeColor(hex, amount, FALLBACK_RGB)
}

const CRANK_SPIN_DURATION_MS = 1200
/** First second: the won capsule fades in at rest under the mouth (no slide/drop motion). */
const CAPSULE_APPEAR_DURATION_MS = 1000
/** Second second: the capsule splits open to reveal the prize (shown via `ResultDialog`, not drawn here). */
const CAPSULE_OPEN_DURATION_MS = 1000

const DOME_JIGGLE_DURATION_MS = 260

/** Per-capsule delay/duration offsets so the dome doesn't jiggle in lockstep — mimics real capsules tumbling unevenly when the crank turns. */
const DOME_JIGGLE_VARIANTS = [
  { delayMs: 0, durationMs: DOME_JIGGLE_DURATION_MS },
  { delayMs: -70, durationMs: DOME_JIGGLE_DURATION_MS + 40 },
  { delayMs: -140, durationMs: DOME_JIGGLE_DURATION_MS - 30 },
  { delayMs: -40, durationMs: DOME_JIGGLE_DURATION_MS + 20 },
  { delayMs: -110, durationMs: DOME_JIGGLE_DURATION_MS - 50 },
  { delayMs: -20, durationMs: DOME_JIGGLE_DURATION_MS + 60 },
  { delayMs: -90, durationMs: DOME_JIGGLE_DURATION_MS + 30 },
  { delayMs: -160, durationMs: DOME_JIGGLE_DURATION_MS - 20 },
  { delayMs: -55, durationMs: DOME_JIGGLE_DURATION_MS + 50 },
] as const

function jiggleStyle(index: number, active: boolean) {
  if (!active) {
    return
  }
  const variant = DOME_JIGGLE_VARIANTS[index % DOME_JIGGLE_VARIANTS.length]
  return {
    animationDelay: `${variant.delayMs}ms`,
    animationDuration: `${variant.durationMs}ms`,
  }
}

